"""Regenerates tests/lib/restricted_env.lua from Blizzard's own source.

The restricted ("secure snippet") environment only exposes what Blizzard_RestrictedAddOnEnvironment sets up:
RESTRICTED_FUNCTIONS_SCOPE, DIRECT_MACRO_CONDITIONAL_NAMES and ENV.* in RestrictedEnvironment.lua, the
rtable functions and table namespace in RestrictedExecution.lua, and the frame handle methods (HANDLE:*) in
RestrictedFrames.lua. Run after updating the UI source clone:

    python -I tests/tools/gen_restricted_env.py F:/Projects/wow-ui-source-forever
"""
import os
import re
import subprocess
import sys

clone = sys.argv[1] if len(sys.argv) > 1 else "F:/Projects/wow-ui-source-forever"
src = os.path.join(clone, "Interface", "AddOns", "Blizzard_RestrictedAddOnEnvironment")
env_lua = open(os.path.join(src, "RestrictedEnvironment.lua"), encoding="utf-8").read()
exec_lua = open(os.path.join(src, "RestrictedExecution.lua"), encoding="utf-8").read()
frames_lua = open(os.path.join(src, "RestrictedFrames.lua"), encoding="utf-8").read()


def table_keys(text, start_marker):
    start = text.index(start_marker)
    depth, i = 0, text.index("{", start)
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                body = text[i + 1:j]
                break
    body = re.sub(r"--[^\n]*", "", body)
    # Top-level keys only (nested tables like `table = { ... }` contribute their own name).
    keys, depth = [], 0
    for line in body.split("\n"):
        if depth == 0:
            m = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)\s*=", line)
            if m:
                keys.append(m.group(1))
        depth += line.count("{") - line.count("}")
    return keys


globals_ = set(table_keys(env_lua, "local RESTRICTED_FUNCTIONS_SCOPE"))
names_block = env_lua[env_lua.index("DIRECT_MACRO_CONDITIONAL_NAMES = {"):]
names_block = names_block[:names_block.index("}")]
globals_.update(re.findall(r'"([A-Za-z_][A-Za-z0-9_]*)"', names_block))
globals_.update(re.findall(r"^\s*ENV\.([A-Za-z_][A-Za-z0-9_]*)\s*=", env_lua, re.M))
globals_.update(re.findall(r"^\s*function\s+ENV\.([A-Za-z_][A-Za-z0-9_]*)", env_lua, re.M))
globals_.update(table_keys(exec_lua, "local LOCAL_Restricted_Global_Functions"))
globals_.update(table_keys(exec_lua, "local LOCAL_Table_Namespace"))
handle_methods = sorted(set(re.findall(r"^\s*function\s+HANDLE:([A-Za-z_][A-Za-z0-9_]*)", frames_lua, re.M)))

try:
    build = subprocess.run(["git", "-C", clone, "log", "-1", "--format=%s"], capture_output=True, text=True).stdout.strip()
except OSError:
    build = "unknown"


def lua_list(names):
    return "\n".join('\t\t"%s",' % n for n in sorted(names))


out = """-- GENERATED by tests/tools/gen_restricted_env.py from Blizzard_RestrictedAddOnEnvironment (%s).
-- Do not edit by hand. What a secure snippet may use: global names, and methods on frame handles.
return {
	build = "%s",
	globals = {
%s
	},
	handleMethods = {
%s
	},
}
""" % (build, build, lua_list(globals_), lua_list(handle_methods))
dst = os.path.join(os.path.dirname(__file__), "..", "lib", "restricted_env.lua")
open(dst, "w", encoding="utf-8", newline="\n").write(out)
print("wrote %s: %d globals, %d handle methods (%s)" % (os.path.normpath(dst), len(globals_), len(handle_methods), build))
